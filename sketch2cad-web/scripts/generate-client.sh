#!/usr/bin/env bash
# Generate src/api/schema.d.ts from the API's committed OpenAPI document (decision D-7).
# CI re-runs this script and fails when `git diff --exit-code src/api/schema.d.ts` is non-empty.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WEB_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
SCHEMA_IN="../sketch2cad-api/openapi.json"
SCHEMA_OUT="src/api/schema.d.ts"
HEADER="// Generated by scripts/generate-client.sh from sketch2cad-api/openapi.json. Do not edit by hand."

cd "${WEB_DIR}"

if [[ ! -f "${SCHEMA_IN}" ]]; then
  echo "OpenAPI document not found: ${WEB_DIR}/${SCHEMA_IN}" >&2
  exit 1
fi

TMP_OUT="$(mktemp "${TMPDIR:-/tmp}/schema.XXXXXX")"
trap 'rm -f "${TMP_OUT}"' EXIT

pnpm exec openapi-typescript "${SCHEMA_IN}" -o "${TMP_OUT}"

mkdir -p "$(dirname "${SCHEMA_OUT}")"
{
  printf '%s\n' "${HEADER}"
  cat "${TMP_OUT}"
} > "${SCHEMA_OUT}"

echo "Wrote ${SCHEMA_OUT}"
