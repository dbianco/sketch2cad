EXPORT_DIR = Path(__file__).resolve().parent
API_DIR = EXPORT_DIR.parents[1]
VERSION = "0.1.0"
META = CaseMeta(
    case_code="EXP-2026-0042",
    title="Colisión en cruce",
    incident_type="Siniestro vial",
    incident_date=date(2026, 10, 1),
    technician="Ana Pérez",
    reviewer="Luis Gómez",
)
ACCESS_RGB = (0x00, 0x8B, 0x9A)  # print colour of L_ACCESS (ACI 4)
LENGTH_TOLERANCE_PT = 0.05 * PT_PER_MM  # 0.05 mm
EXPORT_SCRIPT = (
    "import sys; sys.path.insert(0, sys.argv[1]); import test_pdf_layout as t; "
    "sys.stdout.buffer.write(t.export_variant(sys.argv[2]))"
)


def access_line(number: int, start: list[float], end: list[float]) -> dict[str, Any]:
    return entity(number, "line", "L_ACCESS", {"coords_m": [start, end]})


def measuring_snapshot() -> dict[str, Any]:
    """A 1 m horizontal line and a 5 m diagonal (3-4-5) inside a 20 x 12 m outline."""
    outline = entity(
        1,
        "polyline",
        "L_STRUCTURE",
        {"coords_m": [[0.0, 0.0], [20.0, 0.0], [20.0, 12.0], [0.0, 12.0]], "closed": True},
    )
    return snapshot(
        [outline, access_line(2, [2.0, 2.0], [3.0, 2.0]), access_line(3, [5.0, 5.0], [8.0, 9.0])]
    )


def export_variant(variant: str) -> bytes:
    """``frozen``: mixed entities with an evidence point; ``other``: its next revision."""
    entities = mixed_entities()
    entities[4] = {**entities[4], "evidence_id": "e0000000-0000-4000-8000-000000000001"}
    entities[4]["attributes"] = {"evidence_number": 3, "label": "Casquillo"}
    snap = snapshot(entities)
    if variant == "other":
        snap = {
            **snapshot([*entities, access_line(11, [0.0, 3.0], [1.0, 3.0])]),
            "revision_number": 3,
        }
    return export_pdf(
        snap,
        default_catalog(),
        case_meta=META,
        draft=False,
        generator_version=VERSION,
        frozen_at=FROZEN_AT,
    )


def export(snap: dict[str, Any], **options: Any) -> bytes:
    kwargs: dict[str, Any] = {"draft": False, "frozen_at": FROZEN_AT, **options}
    return export_pdf(snap, default_catalog(), case_meta=META, generator_version=VERSION, **kwargs)


def path_vertices(obj: pdfium.PdfObject) -> list[tuple[float, float]]:
    """Points of the segments of a path object, in page coordinates (points)."""
    matrix = obj.get_matrix()
    vertices: list[tuple[float, float]] = []
    for index in range(pdfium_raw.FPDFPath_CountSegments(obj.raw)):
        segment = pdfium_raw.FPDFPath_GetPathSegment(obj.raw, index)
        x, y = ctypes.c_float(), ctypes.c_float()
        pdfium_raw.FPDFPathSegment_GetPoint(segment, ctypes.byref(x), ctypes.byref(y))
        vertices.append(matrix.on_point(x.value, y.value))
    return vertices


def stroke_rgb(obj: pdfium.PdfObject) -> tuple[int, int, int]:
    r, g, b, a = (ctypes.c_uint() for _ in range(4))
    pdfium_raw.FPDFPageObj_GetStrokeColor(obj.raw, *(ctypes.byref(c) for c in (r, g, b, a)))
    return (r.value, g.value, b.value)


def access_paths(data: bytes) -> list[list[tuple[float, float]]]:
    page = pdfium.PdfDocument(data)[0]
    paths = page.get_objects(filter=[pdfium_raw.FPDF_PAGEOBJ_PATH])
    return [path_vertices(obj) for obj in paths if stroke_rgb(obj) == ACCESS_RGB]


def page_text(data: bytes) -> str:
    return pdfium.PdfDocument(data)[0].get_textpage().get_text_range()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def test_plan_20_by_12_m_on_a3_proposes_1_100() -> None:
    assert propose_scale(Bounds(0.0, 0.0, 20.0, 12.0), A3) == ScaleProposal(100, True)


@pytest.mark.parametrize(
    ("bounds", "sheet", "expected"),
    [
        (None, A4, ScaleProposal(50, True)),
        (Bounds(0.0, 0.0, 9.35, 9.0), A4, ScaleProposal(50, True)),  # 187 x 180 mm, exact
        (Bounds(0.0, 0.0, 9.36, 1.0), A4, ScaleProposal(100, True)),
        (Bounds(0.0, 0.0, 1.0, 9.01), A4, ScaleProposal(100, True)),
        (Bounds(-5.0, -5.0, 13.7, 13.0), A4, ScaleProposal(100, True)),  # 187 x 180 mm, exact
        (Bounds(0.0, 0.0, 18.71, 1.0), A4, ScaleProposal(200, True)),
        (Bounds(0.0, 0.0, 46.75, 1.0), A4, ScaleProposal(250, True)),
        (Bounds(0.0, 0.0, 14.5, 13.35), A3, ScaleProposal(50, True)),  # 290 x 267 mm, exact
        (Bounds(0.0, 0.0, 14.51, 13.35), A3, ScaleProposal(100, True)),
        (Bounds(0.0, 0.0, 145.0, 133.5), A3, ScaleProposal(500, True)),
        (Bounds(0.0, 0.0, 145.1, 10.0), A3, ScaleProposal(500, False)),
    ],
)
def test_scale_is_the_largest_standard_one_that_fits(
    bounds: Bounds | None, sheet: Any, expected: ScaleProposal
) -> None:
    assert propose_scale(bounds, sheet) == expected


def test_auto_sheet_prefers_the_larger_scale_then_a4() -> None:
    assert propose_sheet(Bounds(0.0, 0.0, 5.0, 5.0)) == (A4, ScaleProposal(50, True))
    assert propose_sheet(Bounds(0.0, 0.0, 20.0, 12.0)) == (A3, ScaleProposal(100, True))
    assert propose_sheet(Bounds(0.0, 0.0, 300.0, 1.0)) == (A3, ScaleProposal(500, False))


def test_layout_keeps_15_mm_margins_and_the_title_block_column() -> None:
    for sheet in (A4, A3):
        layout = sheet_layout(sheet)
        frame, area = layout.frame, layout.drawing_area
        assert (frame.x, frame.y) == (MARGIN_MM, MARGIN_MM)
        assert (frame.right, frame.top) == (sheet.width_mm - 15.0, sheet.height_mm - 15.0)
        assert area.right == layout.title_block.x and area.height == frame.height
        assert layout.title_block.y == frame.y and layout.notes.top == frame.top


@pytest.mark.parametrize(("sheet", "spec"), [("A3", A3), ("A4", A4)])
def test_page_is_exactly_the_landscape_sheet(sheet: Any, spec: Any) -> None:
    page = pdfium.PdfDocument(export(snapshot(mixed_entities()), sheet=sheet))[0]
    width, height = page.get_size()
    assert width == pytest.approx(spec.width_mm * PT_PER_MM, abs=1e-3)
    assert height == pytest.approx(spec.height_mm * PT_PER_MM, abs=1e-3)


def test_1_m_line_measures_10_mm_and_5_m_diagonal_50_mm_at_1_100() -> None:
    data = export(measuring_snapshot(), sheet="A3")
    assert "1:100" in page_text(data)
    lengths = sorted(math.dist(path[0], path[-1]) for path in access_paths(data))
    assert lengths == [
        pytest.approx(10.0 * PT_PER_MM, abs=LENGTH_TOLERANCE_PT),
        pytest.approx(50.0 * PT_PER_MM, abs=LENGTH_TOLERANCE_PT),
    ]
    assert lengths[0] == pytest.approx(28.35, abs=0.01)


def test_fixed_scale_is_kept_and_the_plan_is_centred() -> None:
    data = export(measuring_snapshot(), sheet="A3", scale=200)
    one_metre = min(math.dist(path[0], path[-1]) for path in access_paths(data))
    assert one_metre == pytest.approx(5.0 * PT_PER_MM, abs=LENGTH_TOLERANCE_PT)
    page = plan_page(measuring_snapshot(), default_catalog(), sheet="A3", scale=200)
    assert page.transform.point_mm(10.0, 6.0) == sheet_layout(A3).drawing_area.center


