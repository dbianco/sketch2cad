def test_same_revision_in_two_processes_has_the_same_sha256() -> None:
    def run(seed: str, extra: dict[str, str]) -> bytes:
        env = {**os.environ, "PYTHONHASHSEED": seed, **extra}
        return subprocess.run(  # noqa: S603 - fixed argv, no shell
            [sys.executable, "-P", "-c", EXPORT_SCRIPT, str(EXPORT_DIR), "frozen"],
            capture_output=True,
            check=True,
            cwd=API_DIR,
            env=env,
            timeout=120,
        ).stdout

    first = run("1", {})
    time.sleep(2.0)
    second = run("4", {"TZ": "America/Santiago", "SOURCE_DATE_EPOCH": "1700000000"})
    assert first.startswith(b"%PDF-")
    assert sha256(first) == sha256(second) == sha256(export_variant("frozen"))


def test_other_revision_or_freeze_time_has_another_sha256() -> None:
    frozen = export_variant("frozen")
    assert sha256(frozen) != sha256(export_variant("other"))
    later = export(snapshot(mixed_entities()), frozen_at=FROZEN_AT + timedelta(days=1))
    assert sha256(later) != sha256(export(snapshot(mixed_entities())))


def test_invalid_options_are_rejected() -> None:
    snap = snapshot(mixed_entities())
    with pytest.raises(PdfExportError, match="1:75"):
        export(snap, scale=75)
    with pytest.raises(PdfExportError, match="sheet"):
        export(snap, sheet="A2")
    with pytest.raises(ValueError, match="timezone-aware"):
        export(snap, frozen_at=datetime(2026, 10, 21, 9, 30))  # noqa: DTZ001
    with pytest.raises(PdfExportError, match="catalog"):
        export({**snap, "catalog_version": "other-1"})
    with pytest.raises(PdfExportError, match="layer"):
        export(snapshot([entity(1, "line", "L_NOPE", {"coords_m": [[0, 0], [1, 1]]})]))
