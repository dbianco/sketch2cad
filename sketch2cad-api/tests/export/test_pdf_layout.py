"""PDF sheet, scale proposal, vector lengths and reproducibility (REQ-13, H4-3, H4-4, CA-08).

Lengths are measured on the generated bytes: pypdfium2 gives the segments of every path
object (in PDF points) and the stroke colour tells plan lines (``L_ACCESS``, cyan) from the
sheet (black). The cross-process exports run ``export_variant`` in a fresh interpreter
(``EXPORT_SCRIPT``) with another ``PYTHONHASHSEED``, time zone and ``SOURCE_DATE_EPOCH``.
"""

