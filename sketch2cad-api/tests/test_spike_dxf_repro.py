"""Spike 2 (decision D-3, H0-11): byte-level reproducibility of the fixture DXF.

Every DXF is generated by ``spikes/dxf_repro.py --emit <mode>`` in its own interpreter. The
second run of each mode starts 2 s after the first one (the timestamps ezdxf writes have
sub-second resolution, but 2 s is the spec's protocol) and uses another ``PYTHONHASHSEED``.
``raw`` is plain ezdxf output and serves as the negative control.
"""

# ezdxf leaves ``dxfattribs`` parameters unannotated, so strict mode sees them as Unknown.
# pyright: reportUnknownMemberType=false, reportUnknownVariableType=false

import hashlib
import json
import math
import os
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest
from ezdxf.entities.dimension import Dimension
from ezdxf.entities.insert import Insert
from ezdxf.entities.lwpolyline import LWPolyline
from ezdxf.entities.point import Point
from ezdxf.entities.text import Text
from ezdxf.filemanagement import readfile
from ezdxf.tools.juliandate import juliandate

API_DIR = Path(__file__).resolve().parents[1]
SPIKE = API_DIR / "spikes" / "dxf_repro.py"
FIXTURE = API_DIR / "spikes" / "fixtures" / "plan_fixture.json"
SLEEP_SECONDS = 2.0
# With ezdxf 1.4.5 these seeds put LAYOUT and ACDBPLACEHOLDER in opposite order (raw output).
FIRST_SEED, SECOND_SEED = "1", "4"
TOLERANCE_M = 1e-6


def emit(mode: str, seed: str, extra_env: dict[str, str] | None = None) -> bytes:
    env = {**os.environ, "PYTHONHASHSEED": seed, **(extra_env or {})}
    result = subprocess.run(  # noqa: S603 - fixed argv, no shell
        [sys.executable, str(SPIKE), "--emit", mode],
        capture_output=True,
        check=True,
        env=env,
    )
    return result.stdout


def tags(data: bytes) -> list[tuple[str, str]]:
    lines = data.decode("utf-8").split("\n")
    return [(lines[i].strip(), lines[i + 1]) for i in range(0, len(lines) - 1, 2)]


def header_value(data: bytes, name: str) -> str:
    pairs = tags(data)
    index = pairs.index(("9", name))
    return pairs[index + 1][1]


def class_names(data: bytes) -> list[str]:
    pairs = tags(data)
    return [pairs[i + 1][1] for i, pair in enumerate(pairs) if pair == ("0", "CLASS")]


@pytest.fixture(scope="module")
def runs() -> dict[str, tuple[bytes, bytes]]:
    """First run of both modes, a 2 s pause, then the second run with another hash seed."""
    first = {mode: emit(mode, FIRST_SEED) for mode in ("raw", "pinned")}
    time.sleep(SLEEP_SECONDS)
    second = {mode: emit(mode, SECOND_SEED) for mode in ("raw", "pinned")}
    return {mode: (first[mode], second[mode]) for mode in first}


@pytest.fixture(scope="module")
def fixture_data() -> dict[str, Any]:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_pinned_runs_two_seconds_apart_have_the_same_sha256(
    runs: dict[str, tuple[bytes, bytes]],
) -> None:
    first, second = runs["pinned"]
    assert first
    assert hashlib.sha256(first).hexdigest() == hashlib.sha256(second).hexdigest()


def test_raw_runs_differ_in_clock_guid_and_class_order_fields(
    runs: dict[str, tuple[bytes, bytes]],
) -> None:
    first, second = runs["raw"]
    assert first != second
    for name in ("$TDCREATE", "$TDUPDATE", "$FINGERPRINTGUID", "$VERSIONGUID"):
        assert header_value(first, name) != header_value(second, name), name
    assert class_names(first) != class_names(second)
    assert sorted(class_names(first)) == sorted(class_names(second))


@pytest.mark.parametrize("seed", ["0", "7", "10", "random"])
def test_pinned_output_does_not_depend_on_the_hash_seed(
    runs: dict[str, tuple[bytes, bytes]], seed: str
) -> None:
    assert emit("pinned", seed) == runs["pinned"][0]


def test_pinned_output_does_not_depend_on_the_time_zone(
    runs: dict[str, tuple[bytes, bytes]],
) -> None:
    assert emit("pinned", FIRST_SEED, {"TZ": "America/Santiago"}) == runs["pinned"][0]


def test_pinned_header_carries_revision_metadata(
    runs: dict[str, tuple[bytes, bytes]], fixture_data: dict[str, Any]
) -> None:
    data = runs["pinned"][0]
    frozen = datetime.fromisoformat(fixture_data["frozen_at"]).astimezone(UTC)
    expected = juliandate(frozen.replace(tzinfo=None))
    for name in ("$TDCREATE", "$TDUCREATE", "$TDUPDATE", "$TDUUPDATE"):
        assert math.isclose(float(header_value(data, name)), expected, abs_tol=1e-9), name
    assert header_value(data, "$ACADVER") == "AC1027"
    assert header_value(data, "$INSUNITS") == "6"
    assert header_value(data, "$MEASUREMENT") == "1"
    assert header_value(data, "$FINGERPRINTGUID") != header_value(data, "$VERSIONGUID")


def test_reread_audit_is_clean_and_matches_the_fixture(
    runs: dict[str, tuple[bytes, bytes]], fixture_data: dict[str, Any], tmp_path: Path
) -> None:
    path = tmp_path / "plan.dxf"
    path.write_bytes(runs["pinned"][0])
    doc = readfile(path)
    auditor = doc.audit()
    assert (len(auditor.errors), len(auditor.fixes)) == (0, 0)

    for layer in fixture_data["layers"]:
        assert doc.layers.get(layer["name"]).dxf.color == layer["color"]
    msp = doc.modelspace()
    counts = {kind: len(msp.query(kind)) for kind in ("LWPOLYLINE", "TEXT", "INSERT", "DIMENSION")}
    assert counts == {"LWPOLYLINE": 1, "TEXT": 1, "INSERT": 1, "DIMENSION": 1}
    polyline_src, text_src, symbol_src, dim_src = fixture_data["entities"]
    scale = fixture_data["paper_scale"] / 1000.0

    polyline = msp.query("LWPOLYLINE").first
    assert isinstance(polyline, LWPolyline)
    assert polyline.closed and polyline.dxf.layer == "L_STRUCTURE"
    points = list(polyline.vertices())
    assert len(points) == len(polyline_src["points"]) == 4
    for (x, y), (ex, ey) in zip(points, polyline_src["points"], strict=True):
        assert math.isclose(x, ex, abs_tol=TOLERANCE_M) and math.isclose(y, ey, abs_tol=TOLERANCE_M)

    text = msp.query("TEXT").first
    assert isinstance(text, Text)
    assert text.dxf.text == text_src["text"]
    assert (text.dxf.style, text.dxf.layer) == ("S2C_TEXT", "L_TEXT")
    assert text.dxf.insert.isclose((*text_src["insert"], 0.0), abs_tol=TOLERANCE_M)
    assert math.isclose(text.dxf.height, text_src["height_mm_paper"] * scale, abs_tol=TOLERANCE_M)

    insert = msp.query("INSERT").first
    assert isinstance(insert, Insert)
    assert insert.dxf.name == "S2C_evidence_marker"
    assert insert.dxf.insert.isclose((*symbol_src["insert"], 0.0), abs_tol=TOLERANCE_M)
    assert insert.get_attrib_text("evidence_number") == "1"
    assert "evidence_number" in {a.dxf.tag for a in doc.blocks["S2C_evidence_marker"].attdefs()}

    dimension = msp.query("DIMENSION").first
    assert isinstance(dimension, Dimension)
    assert dimension.dxf.text == dim_src["declared_text"]
    assert dimension.dxf.defpoint2.isclose((*dim_src["p1"], 0.0), abs_tol=TOLERANCE_M)
    assert dimension.dxf.defpoint3.isclose((*dim_src["p2"], 0.0), abs_tol=TOLERANCE_M)
    assert dimension.get_geometry_block() is not None

    carrier = msp.query("POINT").first
    assert isinstance(carrier, Point)
    assert carrier.dxf.layer == "L_SHEET" and carrier.dxf.invisible == 1
    xdata = [value for _, value in carrier.get_xdata("SKETCH2CAD")]
    assert f"plan_id={fixture_data['plan_id']}" in xdata
    assert f"snapshot_sha256={fixture_data['snapshot_sha256']}" in xdata
    assert fixture_data["revision_number"] in xdata
